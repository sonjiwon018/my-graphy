# ==================================================
# 그래프 3. 날짜별 10위권 일관객 합계
# ==================================================

st.divider()

st.header("📊 그래프 3. 날짜별 10위권 일관객 합계")

st.write(
    "각 날짜의 박스오피스 10위권 영화의 일관객을 모두 합산하여 "
    "날짜별 전체 관객 규모의 변화를 보여 줍니다."
)


# --------------------------------------------------
# 날짜별 일관객 합계 계산
# --------------------------------------------------

daily_total = (
    df.groupby("날짜", as_index=False)["일관객"]
    .sum()
    .sort_values("날짜")
)


# --------------------------------------------------
# 일관객 합계가 가장 큰 날 TOP 3
# --------------------------------------------------

top3_days = (
    daily_total
    .nlargest(3, "일관객")
    .sort_values("날짜")
)


# ==================================================
# 영역 그래프
# ==================================================

fig3 = px.area(
    daily_total,
    x="날짜",
    y="일관객",
    title="날짜별 박스오피스 10위권 일관객 합계",
    labels={
        "날짜": "날짜",
        "일관객": "10위권 일관객 합계"
    }
)


# --------------------------------------------------
# 마우스를 올렸을 때 표시
# --------------------------------------------------

fig3.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}"
        "<br>"
        "10위권 일관객 합계: %{y:,.0f}명"
        "<extra></extra>"
    )
)


# --------------------------------------------------
# TOP 3 날짜를 그래프 위에 표시
# --------------------------------------------------

for _, row in top3_days.iterrows():

    date = row["날짜"]
    total = row["일관객"]

    fig3.add_annotation(
        x=date,
        y=total,
        text=(
            f"{date.strftime('%m월 %d일')}"
            f"<br>{total:,.0f}명"
        ),
        showarrow=True,
        arrowhead=2,
        ax=0,
        ay=-50,
        font=dict(
            size=13
        ),
        bgcolor="white",
        bordercolor="gray",
        borderwidth=1,
        borderpad=4
    )


# --------------------------------------------------
# X축
# --------------------------------------------------

fig3.update_xaxes(
    tickformat="%Y-%m-%d",
    title_text="날짜",
    showgrid=True
)


# --------------------------------------------------
# Y축
# --------------------------------------------------

fig3.update_yaxes(
    title_text="10위권 일관객 합계(명)",
    tickformat=","
)


# --------------------------------------------------
# 그래프 크기
# --------------------------------------------------

fig3.update_layout(
    height=600,
    hovermode="x",
    margin=dict(
        l=80,
        r=40,
        t=100,
        b=70
    )
)


# --------------------------------------------------
# 그래프 출력
# --------------------------------------------------

st.plotly_chart(
    fig3,
    use_container_width=True
)


# ==================================================
# TOP 3 날짜 표
# ==================================================

st.markdown("### 🏆 일관객 합계가 가장 컸던 날 TOP 3")

for rank, (_, row) in enumerate(
    top3_days.sort_values(
        "일관객",
        ascending=False
    ).iterrows(),
    start=1
):

    st.write(
        f"**{rank}위 — "
        f"{row['날짜'].strftime('%Y년 %m월 %d일')}** : "
        f"{row['일관객']:,.0f}명"
    )


